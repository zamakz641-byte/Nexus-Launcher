import { chromium } from "playwright-core";

const base = process.env.NEXUS_HOME_QA_URL || "http://127.0.0.1:5174";
const browser = await chromium.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem("nexus.onboarding.complete.v1", "true"));
  await page.goto(base);
  const tiles = page.locator(".game-rail__track > .game-tile:not(.game-tile--echo)");
  await tiles.first().waitFor({ timeout: 20_000 });
  await page.waitForTimeout(500);
  const count = await tiles.count();
  if (count < 4) throw new Error(`Need at least 4 games, received ${count}`);
  const selected = () => page.locator('.game-rail__track > .game-tile[data-selected="true"]');
  const activeIndex = async () => Number(await selected().getAttribute("data-index"));
  if (await page.locator(".game-rail__track > .game-tile").count() !== count) errors.push("Rail contains repeated covers before or after the real games");
  if (await activeIndex() !== 0) errors.push("Rail did not start with the first game selected");
  const firstBox = await tiles.first().boundingBox();
  if (!firstBox || firstBox.x > 1920 * .2) errors.push("First game is still positioned near the middle of Home");
  await page.screenshot({ path: "artifacts/qa/home-navigation-start.png" });
  if (await page.locator('.game-rail__track > .game-tile[tabindex="0"]').count() !== 1) errors.push("Only selected tile should be in Tab order");
  await tiles.first().focus();
  await page.keyboard.press("ArrowRight");
  if (await activeIndex() !== 1) errors.push("ArrowRight did not select the next game");
  await page.keyboard.press("ArrowLeft");
  if (await activeIndex() !== 0) errors.push("ArrowLeft did not select the previous game");
  await page.keyboard.press("ArrowLeft");
  if (await activeIndex() !== count - 1) errors.push("ArrowLeft did not wrap to the final game");
  await page.keyboard.press("ArrowRight");
  if (await activeIndex() !== 0) errors.push("ArrowRight did not wrap to the first game");
  const next = page.getByRole("button", { name: /jeu suivant|next game/i });
  if (await next.count()) { await next.click(); if (await activeIndex() !== 1) errors.push("Next control did not select the next game"); }
  else errors.push("Next control is missing");
  if (!(await page.locator(".game-rail__position").innerText()).includes(`2 / ${count}`)) errors.push("Position label did not update");
  await selected().focus();
  await page.keyboard.press("ArrowUp");
  if (!(await page.locator(".hero-game .nexus-button").first().evaluate((element) => element === document.activeElement))) errors.push("Rail → primary action failed");
  await page.keyboard.press("ArrowUp");
  if (!(await page.locator('.top-navigation__route[data-active="true"]').evaluate((element) => element === document.activeElement))) errors.push("Action → top navigation failed");
  await page.keyboard.press("ArrowDown");
  if (!(await page.locator(".hero-game .nexus-button").first().evaluate((element) => element === document.activeElement))) errors.push("Top navigation → action failed");
  await page.keyboard.press("ArrowDown");
  if (!(await selected().evaluate((element) => element === document.activeElement))) errors.push("Action → rail failed");
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("ArrowRight");
  if (await activeIndex() !== 4) errors.push("Repeated ArrowRight inputs skipped or stalled");
  await page.waitForTimeout(800);
  await page.screenshot({ path: "artifacts/qa/home-navigation-desktop.png" });
  await selected().hover();
  await page.mouse.wheel(0, 110);
  await page.waitForTimeout(150);
  if (await activeIndex() !== 0) errors.push("Wheel did not advance and wrap the game rail");
  await page.setViewportSize({ width: 640, height: 720 });
  await page.waitForTimeout(350);
  await page.screenshot({ path: "artifacts/qa/home-navigation-narrow.png" });
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)) errors.push("Home overflows narrow viewport horizontally");
  console.log(JSON.stringify({ games: count, selectedIndex: await activeIndex(), errors }));
  if (errors.length) process.exitCode = 1;
} finally { await browser.close(); }
