import { _electron as electron } from 'playwright-core';
import { mkdir, mkdtemp } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
const root = resolve(import.meta.dirname, '..');
await mkdir(resolve(root, 'artifacts/qa/steam'), { recursive: true });
const profile = await mkdtemp(resolve(root, 'artifacts/qa/steam/profile-'));
const { ELECTRON_RUN_AS_NODE: _, ...env } = process.env;
env.NEXUS_STEAM_ROOT=join(profile,'empty-steam');
const app = await electron.launch({ executablePath: resolve(root, 'node_modules/electron/dist/electron.exe'), args: [root, `--user-data-dir=${profile}`], cwd: root, env });
try {
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.locator('.startup-sequence').waitFor(); await page.keyboard.press('Escape');
  const onboarding=page.locator('.onboarding');await onboarding.waitFor();
  await onboarding.locator('.onboarding__auto').click();await onboarding.locator('.onboarding__footer .onboarding__next').click();
  await onboarding.getByRole('button',{name:'Français',exact:true}).waitFor();await onboarding.locator('.onboarding__footer .onboarding__next').click();
  const notificationChoice=onboarding.getByRole('checkbox');await notificationChoice.waitFor();
  assert.equal(await notificationChoice.getAttribute('aria-checked'),'false');await notificationChoice.click();assert.equal(await notificationChoice.getAttribute('aria-checked'),'true');
  await page.screenshot({path:join(root,'artifacts/qa/steam/onboarding-notifications-fr.png')});
  await notificationChoice.click();await onboarding.locator('.onboarding__footer .onboarding__next').click();
  await onboarding.waitFor({state:'hidden'});
  const status = await page.evaluate(() => window.nexusDesktop.getSteamAccountStatus());
  assert.equal(status.configured, false);
  assert.equal(status.storageAvailable, true);
  assert.equal(await page.evaluate(()=>typeof window.nexusDesktop.saveSteamAccount),'undefined');
  const achievements = await page.evaluate(() => window.nexusDesktop.getSteamAchievements(2281730, 'fr', true));
  assert.equal(achievements.state, 'unconfigured'); assert.deepEqual(achievements.achievements, []);
  assert.equal((await page.evaluate(()=>window.nexusDesktop.getSteamLibrary())).state,'unconfigured');
  const modules=await page.evaluate(()=>window.nexusDesktop.getModuleStatus());
  assert.deepEqual(modules.map(module=>module.id),['game-activity','achievements','notification-overlay']);
  assert.ok(modules.every(module=>module.state==='ready'));
  assert.deepEqual((await page.evaluate(()=>window.nexusDesktop.getGameActivity('not-launched'))).sessions,[]);
  for(const provider of ['epic','gog']) {
    const status=await page.evaluate(provider=>window.nexusDesktop.getStoreAccountStatus(provider),provider);
    assert.equal(status.configured,false);assert.equal(status.storageAvailable,true);
    assert.equal((await page.evaluate(provider=>window.nexusDesktop.getStoreLibrary(provider),provider)).state,'unconfigured');
  }
  await page.locator('.top-navigation__route[href="/settings"]').click();
  await page.getByRole('button', { name: 'Comptes', exact: true }).click();
  await page.getByRole('button', { name: 'Connecter Steam', exact: true }).click();
  await page.locator('.console-steam').waitFor();
  assert.equal(await page.locator('.account-dialog input').count(),0);
  assert.equal(await page.getByRole('button',{name:'Activer',exact:true}).count(),1);
  const layers = await page.locator('.account-dialog').evaluate(element => {
    const rect = element.getBoundingClientRect();
    return { dialog: Number(getComputedStyle(element).zIndex), overlay: Number(getComputedStyle(document.querySelector('.trailer-overlay')).zIndex), hit: element.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + 50)), background: getComputedStyle(element).backgroundColor };
  });
  assert.ok(layers.dialog > layers.overlay); assert.equal(layers.hit, true); assert.equal(await page.locator('.account-dialog').evaluate(element=>getComputedStyle(element).backdropFilter),'blur(28px) saturate(1.25)');
  assert.equal(await page.getByRole('button', { name: 'Ouvrir Steam' }).isEnabled(), true);
  await page.screenshot({ path: join(root, 'artifacts/qa/steam/account-settings.png') });
  await page.screenshot({path:join(root,'artifacts/qa/steam/console-steam-fr.png')});
  const french=await page.locator('.account-dialog').innerText();assert.ok(!/API|SteamID|\.exe/.test(french));
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Connecter Steam',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Connecter Steam',exact:true}).evaluate(element=>element===document.activeElement),true);
  await page.evaluate(()=>localStorage.setItem('nexus.locale.v1','en'));await page.reload();
  const startup=page.locator('.startup-sequence');if(await startup.count())await page.keyboard.press('Escape');
  await page.locator('.top-navigation__route[href="/settings"]').click();
  await page.getByRole('button',{name:'Accounts',exact:true}).click();
  await page.getByRole('button',{name:'Connect Steam',exact:true}).click();
  await page.locator('.console-steam').waitFor();assert.equal(await page.getByRole('button',{name:'Enable',exact:true}).count(),1);
  assert.equal(await page.getByRole('button',{name:'Open Steam',exact:true}).isEnabled(),true);
  await page.screenshot({path:join(root,'artifacts/qa/steam/console-steam-en.png')});await page.keyboard.press('Escape');
  const created=app.waitForEvent('window');
  const connection=page.evaluate(()=>window.nexusDesktop.connectStoreAccount('epic'));
  const login=await created;
  const nativeWindow=await app.browserWindow(login);
  const preferences=await nativeWindow.evaluate(window=>window.webContents.getLastWebPreferences());
  assert.equal(preferences.nodeIntegration,false);assert.equal(preferences.sandbox,true);assert.equal(preferences.contextIsolation,true);
  await nativeWindow.evaluate(window=>window.close());
  const cancelled=await connection;
  assert.equal(cancelled.configured,false);assert.equal(cancelled.error,'cancelled');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ encryptedStorageAvailable: true, realPreloadIPC: true, noSteamKeyInput: true, unconfiguredNotZeroProgress: true, settingsVisible: true, errors }));
} finally { await app.close(); }
